import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

/**
 * Build with esbuild's native binary.
 *
 * The JS API of esbuild talks to the binary over pipes, which sandboxed
 * sessions cannot open; invoking the binary directly with inherited stdio
 * works everywhere and keeps the script dependency-free at build time.
 */

const root = resolve(import.meta.dirname, '..');
const { platform, arch } = process;
// esbuild's platform package layout differs: Windows puts the executable at the
// package root, Linux/macOS under bin/. Probe both (and the .bin shim) so the
// same build script works on the desktop and on Linux CI.
const esbuildDir = join(root, 'node_modules', '@esbuild', `${platform}-${arch}`);
const candidates = [
  join(esbuildDir, platform === 'win32' ? 'esbuild.exe' : join('bin', 'esbuild')),
  join(esbuildDir, platform === 'win32' ? 'esbuild.exe' : 'esbuild'),
  join(root, 'node_modules', '.bin', platform === 'win32' ? 'esbuild.cmd' : 'esbuild'),
];
const binary = candidates.find((candidate) => existsSync(candidate));

if (binary === undefined) {
  console.error('esbuild binary not found in any of:');
  for (const candidate of candidates) console.error(`  ${candidate}`);
  console.error('run `npm install` (dependencies are dev-only; runtime has none)');
  process.exit(1);
}

const targets = [
  ['packages/core/src/index.ts', 'dist/core/index.mjs'],
  ['packages/dsh/src/plugin.ts', 'packages/dsh/dist/plugin.mjs'],
  ['packages/cli/src/main.ts', 'dist/cli/main.mjs'],
];

for (const [entry, outfile] of targets) {
  const result = spawnSync(
    binary,
    [
      entry,
      '--bundle',
      '--format=esm',
      '--platform=node',
      '--target=node24',
      '--sourcemap',
      '--log-level=warning',
      `--outfile=${outfile}`,
    ],
    { cwd: root, stdio: 'inherit' },
  );
  if (result.error !== undefined) {
    console.error(`failed to run esbuild: ${result.error.message}`);
    process.exit(1);
  }
  if (result.status !== 0) {
    console.error(`build failed for ${entry}`);
    process.exit(result.status ?? 1);
  }
  console.log(`built ${outfile}`);
}

// Client half (P3.5): esbuild emits CJS, then we wrap it in the host module
// loader's factory form. The output path is stable: client/client.js is what
// the host serves and what the tarball ships.
const clientEntry = 'packages/dsh/client/src/index.ts';
const clientOut = 'packages/dsh/client/client.js';
const clientTmp = join(root, '.tmp', 'client-bundle.cjs');
mkdirSync(dirname(clientTmp), { recursive: true });
const clientBuild = spawnSync(
  binary,
  [
    clientEntry,
    '--bundle',
    '--format=cjs',
    '--platform=browser',
    '--target=chrome120',
    '--external:react',
    '--external:react/jsx-runtime',
    '--charset=utf8',
    '--log-level=warning',
    `--outfile=${clientTmp}`,
  ],
  { cwd: root, stdio: 'inherit' },
);
if (clientBuild.error !== undefined) {
  console.error(`failed to run esbuild for the client: ${clientBuild.error.message}`);
  process.exit(1);
}
if (clientBuild.status !== 0) {
  console.error(`build failed for ${clientEntry}`);
  process.exit(clientBuild.status ?? 1);
}
const clientCode = readFileSync(clientTmp, 'utf8');
const wrapped = `// @generated by scripts/build.mjs from client/src/index.ts — do not edit.\nwindow.__ModuleLoader__.load({\n  id: "@agent-memory/dsh",\n  factory: (require) => {\n    var module = { exports: {} };\n    var exports = module.exports;\n    (function (module, exports, require) {\n${clientCode}\n    })(module, exports, require);\n    return module.exports;\n  },\n});\n`;
writeFileSync(join(root, clientOut), wrapped);
rmSync(clientTmp, { force: true });
console.log(`built ${clientOut}`);
