#!/usr/bin/env node
/**
 * Generate a profile patch that turns Agent Memory into an opt-in DSH preset.
 *
 * Why: DSH presets (`@deepseek-ai/dsh-agent-preset`) are plain child-plugin
 * lists, so the supported way to vary tools/prompt sections per preset is to
 * clone the shipped `standard` preset and add our plugin to the clone, instead
 * of mounting it at the profile root.
 *
 * Usage:
 *   node scripts/preset.mjs --id memory --mode confirm
 *   node scripts/preset.mjs --id memory-ro --mode readonly > preset.patch.yml
 *
 * Then append the output to `~/.dsh/profiles/desktop/cordis.patch.yml`
 * (or your profile's patch) and pick the preset in Settings -> General.
 * The generated patch first disables the root mount, so memory exists exactly
 * once (inside the new preset).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

function usage(message) {
  if (message) console.error(`preset: ${message}`);
  console.error('usage: node scripts/preset.mjs [--id <name>] [--mode confirm|direct|readonly] [--source <standard.patch.yml>]');
  process.exit(message ? 1 : 0);
}

function parseArgs(argv) {
  const args = { id: 'memory', mode: 'confirm', source: undefined, out: undefined };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--help' || arg === '-h') usage();
    else if (arg === '--id') args.id = argv[++index];
    else if (arg === '--mode') args.mode = argv[++index];
    else if (arg === '--source') args.source = argv[++index];
    else if (arg === '--out') args.out = argv[++index];
    else usage(`unknown argument: ${arg}`);
  }
  if (!/^[a-z0-9][a-z0-9-]*$/.test(args.id ?? '')) usage('--id must be lowercase letters, digits and dashes');
  if (!['confirm', 'direct', 'readonly'].includes(args.mode ?? '')) usage('--mode must be confirm, direct or readonly');
  return args;
}

function findStandardPreset(explicit) {
  const candidates = explicit
    ? [explicit]
    : [
        join(process.env.APPDATA ?? '', 'npm', 'node_modules', '@deepseek-ai', 'dsh', 'node_modules', '@deepseek-ai', 'dsh-web-app', 'presets', 'standard.patch.yml'),
        join(process.env.APPDATA ?? '', 'npm', 'node_modules', '@deepseek-ai', 'dsh', 'node_modules', '@deepseek-ai', 'dsh-web-app', 'presets', 'standard.patch.yml'),
      ];
  for (const candidate of candidates) {
    if (candidate && existsSync(candidate)) return candidate;
  }
  usage('could not find dsh-web-app/presets/standard.patch.yml; pass --source <path>');
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const source = findStandardPreset(args.source);
  const text = readFileSync(source, 'utf8');
  if (!/^\s+plugins:\s*$/m.test(text)) usage(`${source} has no plugins: list`);

  if (!text.includes('id: preset-standard')) usage(`${source} does not declare preset-standard`);
  const renamed = text
    .replace(/- insert:/, '- insert:')
    .replace('id: preset-standard', `id: preset-${args.id}`)
    .replace("id: standard", `id: ${args.id}`)
    .replace(/order: 1\b/, 'order: 50');
  if (renamed === text) usage(`${source} did not contain the expected preset ids`);

  // The preset id inside config is what the registry stores; keep them equal.
  const patch = renamed
    .replace(new RegExp(`id: preset-${args.id}`), `id: preset-${args.id}`)
    .trimEnd();

  const memory = [
    '',
    '          - id: agent-memory',
    "            name: '@agent_memory/dsh'",
    '            config:',
    `              mode: ${args.mode}`,
    '',
  ].join('\n');

  const output = [
    '# Generated by `node scripts/preset.mjs`. Append to your profile patch.',
    '# 1) Disable the root mount so memory is composed by the preset only:',
    '- id: agent-memory',
    '  disabled: true',
    '# 2) Declare the preset (copy of standard + Agent Memory):',
    patch,
    memory,
  ].join('\n');

  if (args.out !== undefined) {
    writeFileSync(args.out, `${output}\n`, 'utf8');
    process.stderr.write(`wrote ${args.out}\n`);
  } else {
    process.stdout.write(`${output}\n`);
  }
}

main();
