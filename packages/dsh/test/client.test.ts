import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');

test('S13.1 the client half is a loader-format bundle with the required registrations', () => {
  const source = readFileSync(join(root, 'client', 'client.js'), 'utf8');
  assert.match(source, /@generated by scripts\/build\.mjs/);
  assert.match(source, /window\.__ModuleLoader__\.load\(\{/);
  assert.match(source, /id: "@agent-memory\/dsh"/);
  assert.match(source, /factory: \(require\) =>/);
  assert.match(source, /ctx\.slots\.inject\(\s*"main"/);
  assert.match(source, /ctx\.slots\.inject\(\s*"sidebar\.panellist"/);
  for (const endpoint of ['list', 'item', 'search', 'export', 'import', 'proposals', 'revise', 'delete', 'profile', 'rules']) {
    assert.match(source, new RegExp(`/api/agent-memory/${endpoint}`));
  }
  assert.match(source, /命令手册/);
  assert.match(source, /导入备份/);
  assert.match(source, /F-01/);
  // P2 human write surfaces: proposals, revise/delete, profile and rules editors.
  assert.match(source, /采纳/);
  assert.match(source, /保存修订/);
  assert.match(source, /保存并重新封存/);
  // UI naming: existing memory shows serial + summary, never a raw mem id.
  assert.match(source, /detail\.data\.serial/);
  assert.match(source, /target\.display/);
  assert.match(source, /replacement\.display/);
  // Proposal cards must expose the full content behind a toggle, not only the summary.
  assert.match(source, /查看详情/);
  assert.match(source, /目标全文/);
  assert.match(source, /修改后摘要/);
  // Backup buttons sit at the end of the toolbar (after the manual button).
  const manualAt = source.indexOf('命令手册');
  const exportAt = source.indexOf('导出备份');
  const importAt = source.indexOf('导入备份');
  assert.ok(manualAt !== -1 && exportAt !== -1 && importAt !== -1);
  assert.ok(manualAt < exportAt && exportAt < importAt);
  // Each kind shows at most 8 rows; the rest live in a nested scroll area.
  assert.match(source, /slice\(0, 8\)/);
  assert.match(source, /还有 \$\{/);
  assert.match(source, /maxHeight: "320px"/);
  // Detail renders above the list (flex order), and switching panels clears it.
  assert.match(source, /order: 1/);
  assert.match(source, /order: 2/);
  assert.match(source, /setExpandedProposal\(null\)/);
  assert.ok(!/detail\.data\.id\s*\}?\s*·/.test(source));
  // The workbench owns a viewport-height scroll container with a styled rail;
  // the host panel does not scroll in windowed mode.
  assert.match(source, /am-memory-scroll/);
  assert.match(source, /::-webkit-scrollbar-thumb/);
  assert.match(source, /overflowY: "auto"/);
  // V3 visual layer: independent tokens, themed root, skeleton and theme toggle.
  assert.match(source, /am-root/);
  assert.match(source, /am-page/);
  assert.match(source, /data-am-theme/);
  assert.match(source, /am-btn/);
  assert.match(source, /am-skeleton/);
  assert.match(source, /--am-accent/);
  assert.match(source, /切换到浅色|切换到深色/);
});

test('S16.1 the token layer defines light and dark themes with a responsive page', () => {
  const styles = readFileSync(join(root, 'client', 'src', 'styles.ts'), 'utf8');
  assert.match(styles, /\[data-am-theme="dark"\]/);
  assert.match(styles, /--am-bg:/);
  assert.match(styles, /--am-accent:/);
  assert.match(styles, /@media \(max-width: 960px\)/);
  assert.match(styles, /prefers-color-scheme: dark/);
  assert.match(styles, /prefers-reduced-motion/);
});

test('S13.2 package.json declares the client half for the host module graph', () => {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as {
    exports?: Record<string, string>;
    files?: string[];
    dsh?: { client?: { platform?: string; inject?: string[] } };
  };
  assert.equal(pkg.exports?.['./client'], './client/client.js');
  assert.ok(pkg.files?.includes('client/client.js'));
  assert.equal(pkg.dsh?.client?.platform, 'web');
  assert.ok(pkg.dsh?.client?.inject?.includes('@deepseek-ai/dsh-client-ui-renderer'));
});
